def _init(directory: Path, *, force: bool) -> dict[str, Any]:
    directory = directory.expanduser().resolve()
    if directory.exists() and any(directory.iterdir()) and not force:
        raise HarnessError("init directory is not empty; use --force to add missing files")
    directory.mkdir(parents=True, exist_ok=True)
    workspace = directory / "workspace"
    workspace.mkdir(exist_ok=True)
    config_path = directory / "dcp-harness.json"
    adapter_path = directory / "task_adapter.py"
    if not config_path.exists():
        write_json(config_path, template())
    if not adapter_path.exists():
        adapter_path.write_text(_ADAPTER_TEMPLATE, encoding="utf-8")
    readme = workspace / "README.txt"
    if not readme.exists():
        readme.write_text(
            "Place only the public starter workspace here. Private verifier data must stay outside this directory.\n",
            encoding="utf-8",
        )
    return {
        "created": str(directory),
        "config": str(config_path),
        "adapter": str(adapter_path),
        "workspace": str(workspace),
        "next": "edit dcp-harness.json and task_adapter.py, then run dcp-harness doctor",
    }


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "init":
            result = _init(Path(args.directory), force=args.force)
            _emit(result, raw_json=False)
            return 0
        config = load_config(args.config)
        if args.command == "doctor":
            loaded = load_adapter(config)
            with tempfile.TemporaryDirectory(prefix="dcp-harness-doctor-") as temporary:
                backend = ClaudeCodeBackend(config, run_root=Path(temporary))
                result = backend.doctor()
            result["adapter_identity_hash"] = loaded.identity_hash
            result["adapter_source_hash"] = loaded.source_hash
            _emit(result, raw_json=args.json)
            return 0 if result["ok"] else 1
        backend = None
        if args.command in {"status", "finalize"}:
            run_root = Path(args.run).expanduser().resolve()
            identity = load_json_object(
                run_root / "registration/agent_interface.json"
            )
            backend = RecordedBackend(identity)
        harness = Harness(config, args.run, backend=backend)
        result = {
            "capture": harness.capture,
            "challenge": harness.challenge,
            "gate3": harness.gate3,
            "finalize": harness.finalize,
            "run": harness.run_all,
            "status": harness.status,
        }[args.command]()
        _emit(result, raw_json=args.json)
        return 0
    except (HarnessError, OSError, ValueError) as exc:
        print(f"dcp-harness: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
