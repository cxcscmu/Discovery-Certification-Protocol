def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="dcp-harness",
        description="Capture and challenge an Auto Research run under DCP.",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    subparsers = parser.add_subparsers(dest="command", required=True)

    init_parser = subparsers.add_parser("init", help="create a minimal audit project")
    init_parser.add_argument("directory")
    init_parser.add_argument(
        "--force", action="store_true",
        help="add missing files in an existing directory; never overwrite files",
    )

    doctor = subparsers.add_parser("doctor", help="check the frozen adapter and agent backend")
    doctor.add_argument("--config", required=True)
    doctor.add_argument("--json", action="store_true")

    for command, help_text in (
        ("capture", "run and capture the main Auto Research lineage"),
        ("challenge", "run registered no-lineage challengers"),
        ("gate3", "run truthful, neutral, and sham pairs"),
        ("finalize", "build and replay-check the DCP Bundle"),
        ("run", "run capture, challenge, Gate 3, and finalization"),
        ("status", "show resumable run state"),
    ):
        item = subparsers.add_parser(command, help=help_text)
        item.add_argument("--config", required=True)
        item.add_argument("--run", required=True)
        item.add_argument("--json", action="store_true")
    return parser


def _emit(value: dict[str, Any], *, raw_json: bool) -> None:
    if raw_json:
        print(json.dumps(value, ensure_ascii=False, sort_keys=True))
        return
    if "phases" in value:
        print(f"DCP run {value['run_id']} for {value['claim_id']}")
        for phase, status in value["phases"].items():
            print(f"  {phase:10s} {status}")
        print(f"  ledger     {'valid' if value.get('ledger_valid') else 'INVALID'}")
        if value.get("bundle"):
            print(f"  bundle     {value['bundle']}")
        return
    if "verdict" in value:
        verdict = value["verdict"]
        print(f"Bundle {value['bundle_id']}")
        print(f"  Core       {verdict['core']}")
        print(f"  Evidence   {verdict['evidence']}")
        print(f"  replay     {'verified' if value['kernel_replay_matches'] else 'FAILED'}")
        return
    print(json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2))


